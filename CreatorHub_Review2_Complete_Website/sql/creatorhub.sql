-- =========================================================
-- CREATORHUB - PostgreSQL Database Schema
-- Safe setup: no DROP TABLE, TRUNCATE, CREATE DATABASE or USE
-- =========================================================

-- 1. STUDENTS
CREATE TABLE IF NOT EXISTS students (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    password_hash CHAR(64) NOT NULL
);

-- 2. PROFILES
CREATE TABLE IF NOT EXISTS profiles (
    student_id INTEGER PRIMARY KEY,
    role_title VARCHAR(100),
    about_me TEXT,
    skills VARCHAR(500),
    work_text TEXT,
    CONSTRAINT fk_profiles_student
        FOREIGN KEY (student_id)
        REFERENCES students(student_id)
        ON DELETE CASCADE
);

-- 3. COLLABORATIONS
CREATE TABLE IF NOT EXISTS collaborations (
    collab_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id INTEGER NOT NULL,
    title VARCHAR(150) NOT NULL,
    category VARCHAR(60) NOT NULL,
    description TEXT NOT NULL,
    required_role VARCHAR(100) NOT NULL,
    status VARCHAR(20) DEFAULT 'Open',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_collaborations_creator
        FOREIGN KEY (creator_id)
        REFERENCES students(student_id)
        ON DELETE CASCADE
);

-- 4. APPLICATIONS
CREATE TABLE IF NOT EXISTS applications (
    application_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collab_id INTEGER NOT NULL,
    applicant_id INTEGER NOT NULL,
    pitch_text TEXT NOT NULL,
    applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT unique_application UNIQUE (collab_id, applicant_id),
    CONSTRAINT fk_applications_collaboration
        FOREIGN KEY (collab_id)
        REFERENCES collaborations(collab_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_applications_applicant
        FOREIGN KEY (applicant_id)
        REFERENCES students(student_id)
        ON DELETE CASCADE
);

-- 5. VOTES
CREATE TABLE IF NOT EXISTS votes (
    vote_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    collab_id INTEGER NOT NULL,
    voter_id INTEGER NOT NULL,
    voted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT unique_vote UNIQUE (collab_id, voter_id),
    CONSTRAINT fk_votes_collaboration
        FOREIGN KEY (collab_id)
        REFERENCES collaborations(collab_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_votes_voter
        FOREIGN KEY (voter_id)
        REFERENCES students(student_id)
        ON DELETE CASCADE
);

-- 6. CHALLENGES
CREATE TABLE IF NOT EXISTS challenges (
    challenge_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    category VARCHAR(60) NOT NULL,
    description TEXT NOT NULL,
    deadline DATE NOT NULL,
    team_size VARCHAR(40) NOT NULL,
    prize VARCHAR(150) NOT NULL
);

-- 7. CHALLENGE PARTICIPANTS
CREATE TABLE IF NOT EXISTS challenge_participants (
    challenge_id INTEGER NOT NULL,
    student_id INTEGER NOT NULL,
    joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_challenge_participants
        PRIMARY KEY (challenge_id, student_id),
    CONSTRAINT fk_participants_challenge
        FOREIGN KEY (challenge_id)
        REFERENCES challenges(challenge_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_participants_student
        FOREIGN KEY (student_id)
        REFERENCES students(student_id)
        ON DELETE CASCADE
);

